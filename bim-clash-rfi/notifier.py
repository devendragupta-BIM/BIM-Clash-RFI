import json
import os
import requests
from dotenv import load_dotenv

load_dotenv()

BOT_TOKEN = os.environ.get("TELEGRAM_BOT_TOKEN", "")
CHAT_ID   = os.environ.get("TELEGRAM_CHAT_ID", "")


def send_telegram(message: str):
    """Send a message via Telegram Bot."""
    if not BOT_TOKEN or BOT_TOKEN == "your_telegram_bot_token_here":
        print("⚠️  Telegram not configured. Add TELEGRAM_BOT_TOKEN to .env")
        return False

    url  = f"https://api.telegram.org/bot{BOT_TOKEN}/sendMessage"
    data = {
        "chat_id"    : CHAT_ID,
        "text"       : message,
        "parse_mode" : "HTML",
    }
    resp = requests.post(url, data=data)
    return resp.status_code == 200


def notify_critical_rfis(summary_json_path: str):
    """Send Telegram alert for every Critical and High severity RFI."""
    with open(summary_json_path) as f:
        data = json.load(f)

    project = data["project"]
    rfis    = data["rfis"]

    # Project summary alert
    critical = [r for r in rfis if r["severity"] == "Critical"]
    high     = [r for r in rfis if r["severity"] == "High"]

    # ── Summary message ──────────────────────────────────
    summary_msg = (
        f"🏗️ <b>BIM CLASH REPORT — {project['name']}</b>\n"
        f"📋 Project: {project['number']}\n"
        f"📅 Date: {project.get('report_date','Today')}\n\n"
        f"📊 <b>CLASH SUMMARY</b>\n"
        f"🔴 Critical : {len(critical)}\n"
        f"🟠 High     : {len(high)}\n"
        f"🟡 Medium   : {len([r for r in rfis if r['severity']=='Medium'])}\n"
        f"🟢 Low      : {len([r for r in rfis if r['severity']=='Low'])}\n"
        f"─────────────────\n"
        f"📁 Total RFIs Generated: {len(rfis)}\n\n"
        f"⚡ <b>Auto-generated by BIM Clash Engine</b>"
    )

    sent = send_telegram(summary_msg)
    if sent:
        print("✅ Telegram summary alert sent")

    # ── Individual alerts for Critical only ──────────────
    for rfi in critical:
        msg = (
            f"🚨 <b>CRITICAL CLASH ALERT</b>\n\n"
            f"🔖 <b>{rfi['rfi_number']}</b>\n"
            f"📌 {rfi['subject']}\n\n"
            f"⚠️ Discipline: {rfi['discipline']}\n"
            f"👤 Assigned To: {rfi['assigned_to']}\n"
            f"📧 Email: {rfi['email']}\n"
            f"⏰ Response Deadline: {rfi['deadline']}\n\n"
            f"🔴 <b>IMMEDIATE ACTION REQUIRED</b>"
        )
        sent = send_telegram(msg)
        if sent:
            print(f"  🔴 Alert sent for {rfi['rfi_number']}")

    print(f"\n📱 Telegram notifications complete")
    print(f"   Critical alerts sent: {len(critical)}")


if __name__ == "__main__":
    summary = "rfi_output/rfi_summary.json"
    if os.path.exists(summary):
        notify_critical_rfis(summary)
    else:
        print("❌ rfi_summary.json not found. Run clash_to_rfi.py first.")
